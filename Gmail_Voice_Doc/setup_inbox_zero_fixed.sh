print_status "Quick start guide created"

# Final summary
echo ""
echo "🎉 INBOX ZERO SETUP COMPLETE!"
echo "=============================="
print_status "Repository cloned and configured"
print_status "Dependencies installed with $PACKAGE_MANAGER"
print_status "Environment file created with secrets"
print_status "Google OAuth credentials configured"
$(if [ "$USE_DOCKER" = true ]; then echo 'print_status "Local database and Redis started"'; else echo 'print_warning "Database and Redis need manual configuration"'; fi)
print_status "Startup script created"

echo ""
print_info "🔑 CRITICAL NEXT STEP:"
echo "   Add your OpenAI API key to apps/web/.env"
echo "   Get it from: https://platform.openai.com/api-keys"

echo ""
print_info "🚀 TO START INBOX ZERO:"
echo "   ./start_inbox_zero.sh"

echo ""
print_info "🌐 THEN OPEN:"
echo "   http://localhost:3000"

echo ""
print_info "📖 READ THE GUIDE:"
echo "   cat QUICK_START.md"

echo ""
print_status "Your Gmail labels are perfectly organized and ready for AI automation!"
echo ""
print_info "Setup completed in: $(pwd)"
